#!/usr/bin/env python3
"""Lists the symbols a PS4 executable imports and writes src/hle/known_names.inc.

Usage: list_imports.py EBOOT.BIN NAMES.json [OUTPUT.inc]

NAMES.json maps NID -> name ({"aBcD...": "sceKernelOpen", ...}). NIDs are one-way hashes, so
the names must come from somewhere else (for example strings found in other programs that call
the same functions). Only the names go into the output file, never code or data from the game.
"""
import json
import struct
import sys

SELF_MAGIC = 0x1D3D154F
PT_DYNAMIC = 2
PT_SCE_DYNLIBDATA = 0x61000000
DT_SCE_IMPORT_LIB = 0x61000015
DT_SCE_STRTAB = 0x61000035
DT_SCE_STRSZ = 0x61000037
DT_SCE_SYMTAB = 0x61000039
DT_SCE_SYMTABSZ = 0x6100003F
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+-"


def read_elf(path):
    data = open(path, "rb").read()
    if struct.unpack_from("<I", data, 0)[0] != SELF_MAGIC:
        return data
    count = struct.unpack_from("<H", data, 0x18)[0]
    header = 0x20 + count * 0x20
    phoff, = struct.unpack_from("<Q", data, header + 0x20)
    phentsize, phnum = struct.unpack_from("<HH", data, header + 0x36)
    phdrs = [struct.unpack_from("<IIQQQQQQ", data, header + phoff + i * phentsize)
             for i in range(phnum)]
    end = max([phoff + phnum * phentsize] + [p[2] + p[5] for p in phdrs])
    out = bytearray(end)
    out[:phoff + phnum * phentsize] = data[header:header + phoff + phnum * phentsize]
    for i in range(count):
        props, offset, filesz, _ = struct.unpack_from("<QQQQ", data, 0x20 + i * 0x20)
        if props & 0x800:
            ph = phdrs[(props >> 20) & 0xFFF]
            out[ph[2]:ph[2] + filesz] = data[offset:offset + filesz]
    return bytes(out)


def imports(elf):
    phoff, = struct.unpack_from("<Q", elf, 0x20)
    phentsize, phnum = struct.unpack_from("<HH", elf, 0x36)
    phdrs = [struct.unpack_from("<IIQQQQQQ", elf, phoff + i * phentsize) for i in range(phnum)]
    dyn = next(p for p in phdrs if p[0] == PT_DYNAMIC)
    blob = next(p for p in phdrs if p[0] == PT_SCE_DYNLIBDATA)[2]
    tags, libs = {}, []
    for i in range(dyn[5] // 16):
        tag, value = struct.unpack_from("<qQ", elf, dyn[2] + i * 16)
        if tag == 0:
            break
        if tag == DT_SCE_IMPORT_LIB:
            libs.append(value)
        tags[tag] = value
    strtab = blob + tags[DT_SCE_STRTAB]

    def cstr(offset):
        return elf[strtab + offset:elf.index(b"\0", strtab + offset)].decode()

    lib_names = {v >> 48: cstr(v & 0xFFFFFFFF) for v in libs}
    result = set()
    symtab = blob + tags[DT_SCE_SYMTAB]
    for i in range(tags[DT_SCE_SYMTABSZ] // 24):
        st_name, _, _, st_shndx, st_value, _ = struct.unpack_from("<IBBHQQ", elf, symtab + i * 24)
        parts = cstr(st_name).split("#") if st_name else []
        if len(parts) != 3 or st_shndx != 0:
            continue
        lib_id = 0
        for ch in parts[1]:
            lib_id = lib_id * 64 + ALPHABET.index(ch)
        result.add((lib_names.get(lib_id, "?"), parts[0]))
    return sorted(result)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    names = json.load(open(sys.argv[2]))
    out_path = sys.argv[3] if len(sys.argv) > 3 else "src/hle/known_names.inc"
    entries = imports(read_elf(sys.argv[1]))
    lines = ["// Generated by tools/list_imports.py: names of the game's imports.\n"]
    missing = 0
    for lib, nid in sorted(entries, key=lambda e: (e[0], names.get(e[1], "~" + e[1]))):
        if nid in names:
            lines.append(f'{{"{lib}", "{names[nid]}"}},\n')
        else:
            lines.append(f"// {lib}: NID {nid} with no known name\n")
            missing += 1
    open(out_path, "w").writelines(lines)
    print(f"{len(entries)} imports, {missing} unnamed -> {out_path}")


if __name__ == "__main__":
    main()
